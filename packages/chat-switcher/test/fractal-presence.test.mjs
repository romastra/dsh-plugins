  const domains = [], original = h.HashRandom.prototype.word;
  h.HashRandom.prototype.word = function () { domains.push(new TextDecoder().decode(this.seed)); return original.call(this); };
  assert.equal(h.hasMosaicFractal('legacy'), false);
