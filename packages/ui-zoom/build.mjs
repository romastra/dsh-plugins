import { readFile, writeFile } from 'node:fs/promises';
const read = file => readFile(new URL(file, import.meta.url), 'utf8');
const sources = await Promise.all(['src/scale.js', 'src/geometry.js', 'src/core.js', 'src/local-preference.js', 'src/controller.js', 'src/popup.js', 'src/coordinates.js', 'src/client.js'].map(read));
const body = sources.map(source => source.replace(/^import .+ from '\.\/.+';\r?\n/gm, '').replace(/^export /gm, '')).join('\n');
const artifact = `// Generated by build.mjs; React is the only runtime import.\nwindow.__ModuleLoader__.load({\n  id: '@local/ui-zoom',\n  factory(require) {\n${body}\n    return createPlugin(require('react'));\n  }\n});\n`;
await writeFile(new URL('client-v6.js', import.meta.url), artifact, 'utf8');
console.log('Built UI zoom client.');
