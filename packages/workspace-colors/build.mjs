import { readFile, writeFile } from 'node:fs/promises';
const files = ['palette.js', 'src/copy.js', 'src/menu.js', 'src/store.js', 'src/color-source.js', 'src/session-colors.js', 'src/client-main.js'];
const chunks = [];
for (const file of files) {
  const source = await readFile(new URL(file, import.meta.url), 'utf8');
  chunks.push(source.replace(/^import .+;\r?\n/gm, '').replace(/^export (?=(?:const|function|class|async function)\b)/gm, ''));
}
const output = `// Generated by build.mjs; React is the only runtime import.\nwindow.__ModuleLoader__.load({\n  id: '@local/workspace-colors',\n  factory(require) {\n${chunks.join('\n')}\n    return createPlugin(require('react'));\n  },\n});\n`;
await writeFile(new URL('client-v3.js', import.meta.url), output);
console.log('Built client-v3.js');
