import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const settle = async () => { for (let i = 0; i < 4; i++) await Promise.resolve(); };

function source(initial) {
  let snapshot = initial;
  const listeners = new Set();
  return {
    getSnapshot: () => snapshot,
    subscribe(fn) { listeners.add(fn); return () => listeners.delete(fn); },
    set(value) { snapshot = value; for (const fn of [...listeners]) fn(); },
    get listenerCount() { return listeners.size; },
  };
}
function scope() {
  const effects = new Set();
  return {
    effect(start) {
      const cleanup = start();
      let active = true;
      const off = () => {
        if (!active) return;
        active = false;
        effects.delete(off);
        cleanup?.();
      };
      effects.add(off);
      return off;
    },
    dispose() { for (const off of [...effects].reverse()) off(); },
    get effectCount() { return effects.size; },
  };
}
async function load() {
  let definition;
  vm.runInNewContext(await read('client.js'), {
    window: { __ModuleLoader__: { load(value) { definition = value; } } },
    queueMicrotask, console,
  });
  const imports = [];
  const plugin = definition.factory(name => {
    imports.push(name);
    assert.equal(name, 'react');
    // No React or DOM renderer is emulated: apply registers the real component,
    // whose browser rendering remains a separate manual verification step.
    return {};
  });
  return { definition, plugin, imports };
}

test('generated Client is exactly the reviewed sources, with only React external', async () => {
  const logic = (await read('src/preservation.js')).replace(/^export /gm, '');
  const entry = await read('src/client-entry.js');
  const expected = `// Generated by build.mjs from the reviewed source; no runtime imports except React.\n(() => {\n${logic}\n${entry}\n})();\n`;
  assert.equal(await read('client.js'), expected);
  const manifest = JSON.parse(await read('package.json'));
  const { definition, plugin, imports } = await load();
  assert.equal(definition.id, manifest.name);
  assert.deepEqual(imports, ['react']);
  assert.equal(typeof plugin.apply, 'function');
  assert.ok(plugin.inject.includes('conversation'));
  assert.ok(plugin.inject.includes('uiSession'));
});

test('Client apply wires lifetime, overlay, read-only status and complete unload', async () => {
  const { plugin } = await load();
  const ctx = scope();
  const sessionCtx = scope();
  const inputState = source({ draft: '', draftRev: 0, attachmentIds: [], phase: 'plain' });
  const sessionState = source({ blank: true, removed: false });
  const binding = { sessionId: 'blank', ctx: sessionCtx, session: sessionState };
  sessionState.projections = { faceOf: () => source('minimal') };
  const workspaces = { list: source({ archivedSessionIds: [] }) };
  let holds = 0;
  let releases = 0;
  const sessions = {
    list: source({ byId: { blank: { blank: true, projectionValues: { agentPreset: 'minimal' } } } }),
    binding: id => id === 'blank' ? binding : undefined,
    async create(options) { return options?.sessionId ?? 'new'; },
    retain(id, options) {
      assert.equal(id, 'blank');
      assert.equal(options.source, 'draftPreservation');
      holds += 1;
      return { binding, ready: Promise.resolve(binding), release() { releases += 1; } };
    },
  };
  const originalCreate = sessions.create;
  let descriptor;
  let overlay;
  let provider;
  let overlayDisposed = false;
  const services = {
    sessions, workspaces,
    conversation: { input: { for: () => ({ state: inputState }) } },
    uiSession: {
      provide(value) {
        descriptor = value;
        descriptor.resolve(binding);
        return () => { descriptor = undefined; };
      },
    },
    slots: {
      inject(name, callback) {
        assert.equal(name, 'conversation.input.overlay');
        return ctx.effect(callback);
      },
      register(options, Component) {
        overlay = { options, Component };
        return () => { overlayDisposed = true; };
      },
    },
    cordisInspect: {
      register(value) { provider = value; return () => { provider = undefined; }; },
    },
  };
  ctx.get = name => services[name];
  ctx.inject = (dependencies, callback) => {
    assert.deepEqual(Array.from(dependencies), ['cordisInspect']);
    callback(ctx);
  };
  plugin.apply(ctx);
  assert.notEqual(sessions.create, originalCreate);
  assert.equal(typeof overlay.Component, 'function');
  assert.equal(overlay.options.id, 'draft-preservation:1.0.0');
  assert.equal(provider.manifest.id, 'DraftPreservation');
  descriptor.resolve(binding);
  await settle();
  assert.equal(inputState.listenerCount, 1);
  assert.equal(holds, 0, 'empty draft should not hold a Session');
  inputState.set({ draft: 'private text', draftRev: 1, attachmentIds: ['image'], phase: 'plain' });
  await settle();
  assert.equal(holds, 1);
  const before = { holds, releases };
  const status = await provider.query('status', {});
  assert.equal(status.version, '1.0.0');
  assert.equal(status.presetReuseProtected, true);
  assert.equal(status.attachments, 1);
  assert.equal(status.retainedSessions, 1);
  assert.equal(status.errors, 0);
  assert.ok(!JSON.stringify(status).includes('private text'));
  assert.ok(!JSON.stringify(status).includes('image'));
  assert.deepEqual({ holds, releases }, before, 'inspection must remain read-only');
  await assert.rejects(provider.query('not-a-method'), /Unknown method/);
  ctx.dispose();
  await settle();
  assert.equal(sessions.create, originalCreate);
  assert.equal(releases, 1);
  assert.equal(inputState.listenerCount, 0);
  assert.equal(sessionState.listenerCount, 0);
  assert.equal(workspaces.list.listenerCount, 0);
  assert.equal(sessionCtx.effectCount, 0);
  assert.equal(descriptor, undefined);
  assert.equal(provider, undefined);
  assert.equal(overlayDisposed, true);
  sessionCtx.dispose();
  assert.equal(releases, 1, 'dual-owner disposal must be idempotent');
});

test('display resources and exact DSH compatibility are included', async () => {
  const manifest = JSON.parse(await read('package.json'));
  assert.equal(manifest.engines.dsh, '0.2.2-rc.3 || 0.2.2-rc.5');
  assert.equal(manifest.exports['./icon'], './icon.svg');
  for (const language of ['en', 'ru', 'zh']) {
    const locale = JSON.parse(await read(`locale/${language}.json`));
    assert.ok(locale.meta.title);
    assert.ok(locale.meta.description);
  }
  const icon = await read('icon.svg');
  assert.match(icon, /viewBox="0 0 36 36"/);
  assert.doesNotMatch(icon, /<script|<image|<foreignObject|<style|<text|onload=/);
  assert.ok(Buffer.byteLength(icon) < 256 * 1024);
  assert.match(await read('README.md'), /0\.2\.2-rc\.3/);
});
