import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('./', import.meta.url);
const choices = (await readFile(new URL('src/choices.js', root), 'utf8')).replace(/^export /gm, '');
const client = (await readFile(new URL('src/client.js', root), 'utf8'))
  .replace(/^import .* from '\.\/choices\.js';\r?\n/m, '')
  .replace(/^export /gm, '');
const artifact = `// Generated by build.mjs from src/choices.js and src/client.js.\nwindow.__ModuleLoader__.load({\n  id: '@local/reasoning-depth',\n  factory(require) {\n${choices}\n${client}\n    return createPlugin(require('react'));\n  }\n});\n`;
await writeFile(new URL('client.js', root), artifact, 'utf8');
console.log('Built reasoning-depth client.js (React is the only runtime import).');
